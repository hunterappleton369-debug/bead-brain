#!/usr/bin/env node
// build-members.mjs — builds what the member area reads, from the product files in docs/products.
// The app never loads anything from docs/ at runtime; this script copies or converts it at build time.
//
//   node tools/build-members.mjs            all four steps below
//   node tools/build-members.mjs --check    step 2 only (no files written)
//
// 1. js/lesson-notes.js   copied from docs/products/practice-handouts/tools/lesson-notes.mjs (the written half of each sheet)
// 2. check                js/handouts.js must print exactly the 86 sheets in docs/products/practice-handouts/samples
//                         for the samples' seed, and every problem must pass the re-check. Exit 1 if not.
// 3. library/*.json       the Prodigy Secrets Program (docs/products/prodigy-secrets-program/*.md) as HTML pages,
//                         split at the book's page breaks, for #/library in the app.
// 4. library/playbook.json  Child Prodigy Secrets Playbook (docs/products/playbook.md), the $27 add-on, with the same
//                         converter, split at the book's chapter breaks (---), for #/playbook in the app.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve, relative } from 'node:path';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PRODUCTS = join(REPO, 'docs/products');
const checkOnly = process.argv.includes('--check');
const rel = p => relative(REPO, p);

// ───────────── 1. lesson notes ─────────────
if (!checkOnly) {
  const src = join(PRODUCTS, 'practice-handouts/tools/lesson-notes.mjs');
  const body = readFileSync(src, 'utf8');
  const head = `// GENERATED by tools/build-members.mjs from ${rel(src)}. Edit that file, then rerun the build.\n`;
  writeFileSync(join(REPO, 'js/lesson-notes.js'), head + body);
  console.log(`wrote js/lesson-notes.js`);
}

// ───────────── 2. the browser port prints the same sheets as the CLI ─────────────
const { buildSheet, BASE_SEED, SHEETS } = await import(join(REPO, 'js/handouts.js'));
{
  const dir = join(PRODUCTS, 'practice-handouts/samples');
  const pad2 = n => String(n).padStart(2, '0');
  let same = 0, differ = 0, bad = 0, problems = 0;
  for (const { stage, keys } of SHEETS) for (const key of keys) {
    const sheet = buildSheet(stage, key, BASE_SEED);
    problems += sheet.drills.reduce((a, x) => a + x.items.length, 0);
    if (sheet.problems.length) { bad++; console.error(`stage ${stage} ${key}: ${sheet.problems.slice(0, 3).join(' | ')}`); }
    const file = join(dir, `stage-${pad2(stage)}-${key === 'boss' ? 'boss-prep' : key}.md`);
    const md = readFileSync(file, 'utf8')
      .replace(/^<!--[^\n]*-->\n\n/, '').replace(/\n\n<!-- status: ready -->\n$/, '');
    const mine = sheet.pages.join('\n\n<div class="page-break"></div>\n\n');
    if (md === mine) same++; else { differ++; if (differ <= 3) console.error(`differs from the sample: ${rel(file)}`); }
  }
  console.log(`handouts: ${same} of ${same + differ} sheets match the samples exactly, ${problems} problems, ${bad} sheet(s) with a failed re-check`);
  if (differ || bad) {
    console.error('js/handouts.js is out of step with docs/products/practice-handouts/tools/make-handouts.mjs (or the samples are stale). Fix before shipping.');
    process.exit(1);
  }
}
if (checkOnly) process.exit(0);

// ───────────── 3. the lesson library ─────────────
const { STAGES } = await import(join(REPO, 'js/curriculum.js'));
const LIB = join(PRODUCTS, 'prodigy-secrets-program');
const OUT = join(REPO, 'library');
mkdirSync(OUT, { recursive: true });

const escH = s => s.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
function inline(s) {
  return escH(s)
    .replace(/\[beads: (\d+)\]/g, '<span class="beads" data-n="$1" role="img" aria-label="soroban picture"></span>')
    .replace(/_{4,}/g, '<span class="blank"></span>')
    .replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
    .replace(/(^|[^*\w])\*(?=\S)(.+?)\*(?!\*)/g, '$1<em>$2</em>');
}
const alignOf = a => (a.startsWith(':') && a.endsWith(':') ? 'c' : a.endsWith(':') ? 'r' : 'l');
function table(lines) {
  const row = l => l.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map(c => c.trim());
  const head = row(lines[0]), al = row(lines[1]).map(alignOf);
  const body = lines.slice(2).map(row);
  const td = (c, i, tag) => {
    const cls = [`a-${al[i] || 'l'}`]; if (/^_{4,}$/.test(c)) cls.push('ans');
    return `<${tag} class="${cls.join(' ')}">${/^_{4,}$/.test(c) ? '' : inline(c)}</${tag}>`;
  };
  const stack = al.length && al.every(a => a === 'r');
  return `<div class="lib-table-wrap"><table class="lib-table${stack ? ' stack' : ''}"><thead><tr>${head.map((c, i) => td(c, i, 'th')).join('')}</tr></thead><tbody>${body.map(r => `<tr>${r.map((c, i) => td(c, i, 'td')).join('')}</tr>`).join('')}</tbody></table></div>`;
}
// The book's Markdown is a small, regular subset: headings, paragraphs, lists, tables, ✎ quotes, page breaks.
// The first heading on a page becomes its h2 title; later # and ## become h3, ### h4.
function toHTML(md) {
  const out = []; let para = [], list = null, quote = [], tbl = [], titled = false;
  const flush = () => {
    // A paragraph line that starts with a signed number (+4 = +5 −1) is a formula row: keep its line break.
    if (para.length) { out.push(`<p>${inline(para.map((l, i) => (i ? (/^[+−]\d/.test(l) ? '\u0001' : ' ') : '') + l).join('')).replace(/\u0001/g, '<br>')}</p>`); para = []; }
    if (list) { out.push(`<${list.tag}>${list.items.map(i => `<li>${inline(i)}</li>`).join('')}</${list.tag}>`); list = null; }
    if (quote.length) {
      const text = quote.join(' ');
      out.push(/^✎/.test(text) ? `<div class="parent-line"><span class="who">Parent line</span>${inline(text.replace(/^✎\s*/, ''))}</div>` : `<blockquote>${inline(text)}</blockquote>`);
      quote = [];
    }
    if (tbl.length) { out.push(table(tbl)); tbl = []; }
  };
  for (const raw of md.split('\n')) {
    const line = raw.trimEnd();
    let m;
    if (!line.trim()) { flush(); continue; }
    if (/^\|/.test(line)) { if (!tbl.length) flush(); tbl.push(line); continue; }
    if (tbl.length) flush();
    if ((m = line.match(/^(#{1,4}) (.*)$/))) {
      flush();
      const lv = titled ? Math.max(3, m[1].length + 1) : 2;
      out.push(`<h${lv}${titled ? '' : ' class="page-title"'}>${inline(m[2])}</h${lv}>`); titled = true; continue;
    }
    if (/^---+$/.test(line)) { flush(); out.push('<hr>'); continue; }
    if ((m = line.match(/^<small>(.*)<\/small>$/))) { flush(); out.push(`<p class="small faint">${inline(m[1])}</p>`); continue; }
    if ((m = line.match(/^> ?(.*)$/))) { if (para.length || list) flush(); quote.push(m[1]); continue; }
    if ((m = line.match(/^- (.*)$/))) { if (para.length || quote.length || (list && list.tag !== 'ul')) flush(); list = list || { tag: 'ul', items: [] }; list.items.push(m[1]); continue; }
    if ((m = line.match(/^\d+\. (.*)$/))) { if (para.length || quote.length || (list && list.tag !== 'ol')) flush(); list = list || { tag: 'ol', items: [] }; list.items.push(m[1]); continue; }
    if (list && /^\s{2,}\S/.test(raw)) { list.items[list.items.length - 1] += ' ' + line.trim(); continue; }
    if (quote.length) flush();
    para.push(line.trim());
  }
  flush();
  return out.join('\n');
}
function kindOf(title) {
  if (/^Lesson \d+\.\d+/.test(title)) return 'lesson';
  if (/quest cards$/.test(title)) return 'quests';
  if (/answers\b/i.test(title)) return 'answers';
  if (/^What the trainer adds/.test(title)) return 'trainer';
  if (/^Boss \d+ ·/.test(title)) return 'boss';
  if (/Boss$/.test(title)) return 'boss-note';
  return 'opener';
}
// One book file → { title, sections: [{ kind, title, html }] }. The Program splits at its page-break divs;
// the Playbook (step 4) passes its own folder, its chapter breaks and its own page kinds.
const PAGE_BREAK = /^<div class="page-break"><\/div>$/m;
function convert(file, extra = {}, { dir = LIB, split = PAGE_BREAK, kind = kindOf } = {}) {
  const md = readFileSync(join(dir, file), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const chunks = md.split(split).map(s => s.trim()).filter(Boolean);
  const sections = chunks.map((chunk, i) => {
    const title = (chunk.match(/^#{1,3} (.*)$/m) || [, `Page ${i + 1}`])[1].trim();
    const s = { kind: kind(title, i), title, html: toHTML(chunk) };
    const m = title.match(/^Lesson (\d+)\.(\d+) · (.*)$/);
    if (m) {
      const stage = STAGES[Number(m[1]) - 1], lesson = stage?.lessons[Number(m[2]) - 1];
      if (!lesson) throw new Error(`${file}: "${title}" has no lesson in js/curriculum.js`);
      if (lesson.title !== m[3]) console.warn(`  note: ${file} "${m[3]}" vs curriculum "${lesson.title}"`);
      Object.assign(s, { no: `${m[1]}.${m[2]}`, key: lesson.key });
    }
    const b = title.match(/^Boss (\d+) ·/);
    if (b) s.stage = Number(b[1]);
    return s;
  });
  const title = sections[0].title;
  const stray = sections.map(s => s.html).join('').match(/\*\*|\[beads|(?<![\w/])\*(?=\w)/);
  if (stray) throw new Error(`${file}: Markdown left in the HTML near "${stray[0]}"`);
  return { title, ...extra, sections };
}

const books = [{ id: 'start', file: '00-how-to-use.md' }, ...STAGES.map(s => ({ id: `stage-${String(s.n).padStart(2, '0')}`, file: readdirSync(LIB).find(f => f.startsWith(`stage-${String(s.n).padStart(2, '0')}-`)), stage: s.n })), { id: 'bosses', file: 'boss-tests.md' }];
const index = [];
for (const b of books) {
  const doc = convert(b.file, b.stage ? { stage: b.stage } : {});
  writeFileSync(join(OUT, `${b.id}.json`), JSON.stringify(doc));
  index.push({ id: b.id, stage: b.stage || null, title: doc.title, pages: doc.sections.length, lessons: doc.sections.filter(s => s.kind === 'lesson').length });
}
writeFileSync(join(OUT, 'index.json'), JSON.stringify({ built: new Date().toISOString().slice(0, 10), source: rel(LIB), books: index }, null, 1));
console.log(`library: ${index.length} books, ${index.reduce((a, b) => a + b.pages, 0)} pages, ${index.reduce((a, b) => a + b.lessons, 0)} lessons → ${rel(OUT)}/`);

// ───────────── 4. the Playbook ─────────────
// Pages = the book's chapter breaks (a line of ---). The printed Contents page is left out: its page numbers are
// the paperback's, and the app shows its own chapter list. Chapters carry `no` for the list ("Chapter 3").
{
  const file = 'playbook.md';
  const kind = (title, i) => (i === 0 ? 'cover' : /^Chapter \d+:/.test(title) ? 'chapter' : /^Page \d+$/.test(title) ? 'copyright' : /^Contents$/.test(title) ? 'contents' : 'appendix');
  const doc = convert(file, {}, { dir: PRODUCTS, split: /^---+$/m, kind });
  const sections = doc.sections.filter(s => s.kind !== 'contents').map(s => {
    if (s.kind === 'copyright') return { ...s, title: 'Copyright' };
    const m = s.title.match(/^Chapter (\d+): (.*)$/);
    return m ? { ...s, no: Number(m[1]), title: m[2] } : s;
  });
  if (!sections.some(s => s.kind === 'chapter')) throw new Error(`${file}: no chapters found`);
  const out = { title: doc.title, built: new Date().toISOString().slice(0, 10), source: rel(join(PRODUCTS, file)), sections };
  writeFileSync(join(OUT, 'playbook.json'), JSON.stringify(out));
  console.log(`playbook: ${sections.length} pages, ${sections.filter(s => s.kind === 'chapter').length} chapters → ${rel(join(OUT, 'playbook.json'))}`);
}

// ───────────── 5. the 3-Night Quick-Start ─────────────
// docs/products/welcome-card.md (the digital card every kit buyer gets in email Q1) → library/quickstart.json for
// #/quickstart in the app, and the same copy as a section of free-abacus/thanks.html between the quickstart markers.
// One source, so the email, the thank-you page and the account page always say the same thing.
{
  const file = join(PRODUCTS, 'welcome-card.md');
  const md = readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '').split(/^---+$/m).slice(1).join('\n').trim();
  const blocks = md.split(/\n\s*\n/).map(b => b.trim()).filter(Boolean);
  const title = (blocks.shift().match(/^## (.*)$/) || [])[1];
  if (!title) throw new Error(`${rel(file)}: expected "## <title>" after the first ---`);
  const doc = { title, built: new Date().toISOString().slice(0, 10), source: rel(file), intro: [], every: '', nights: [], after: '' };
  for (const b of blocks) {
    let m;
    if ((m = b.match(/^\*\*Every night:\*\*\s*(.*)$/s))) doc.every = inline(m[1]);
    else if ((m = b.match(/^\*\*Night (\d) · (.*?)\*\*\n(.*)\nWhy tonight matters: (.*)$/s))) doc.nights.push({ n: Number(m[1]), title: inline(m[2]), body: inline(m[3]), why: inline(m[4]) });
    else if (/^\*\*Night 4:\*\*/.test(b)) doc.after = inline(b);
    else doc.intro.push(inline(b));
  }
  if (doc.nights.length !== 3 || !doc.every || !doc.after) throw new Error(`${rel(file)}: expected three Night blocks, an "Every night" line and a Night 4 line`);
  writeFileSync(join(OUT, 'quickstart.json'), JSON.stringify(doc));

  const thanks = join(REPO, 'free-abacus/thanks.html');
  const html = readFileSync(thanks, 'utf8');
  const section = `<!-- quickstart:start · generated by tools/build-members.mjs from ${rel(file)}; edit that file, then rerun the build -->
  <section class="fn-sec" id="quickstart">
    <span class="eyebrow green">Your 3-Night Quick-Start</span>
    <h2>${title}</h2>
    ${doc.intro.map(p => `<p>${p}</p>`).join('\n    ')}
    <p><b>Every night:</b> ${doc.every}</p>
    <ol class="pathway">
      ${doc.nights.map(n => `<li><div><b>Night ${n.n} · ${n.title}</b><span>${n.body}</span><span class="why">Why tonight matters: ${n.why}</span></div></li>`).join('\n      ')}
    </ol>
    <p style="margin-top: 14px">${doc.after}</p>
    <a class="btn cta cf" href="https://childphenoms.com/#/stage/1" target="_blank" rel="noopener" style="margin-top: 18px">Start Night 1 On The Screen Abacus →<small>Stage 1 is open now. Sign in with the email you ordered with.</small></a>
  </section>
  <!-- quickstart:end -->`;
  const marked = /<!-- quickstart:start[\s\S]*?<!-- quickstart:end -->/;
  if (!marked.test(html)) throw new Error(`${rel(thanks)}: no <!-- quickstart:start --> … <!-- quickstart:end --> markers to fill`);
  writeFileSync(thanks, html.replace(marked, section));
  console.log(`quick-start: ${doc.nights.length} nights → library/quickstart.json and the quickstart section of ${rel(thanks)}`);
}
